-- เลขที่ใบจอง
--
-- เดิมช่อง "เลขที่ใบจอง" ในตัวช่วยทำสัญญาให้พิมพ์เอง และตัวการจองเองไม่มีเลขที่เลย
-- มีแต่ booking_id ที่เป็นเลขภายในของฐานข้อมูล ซึ่งไม่ใช่เลขที่จะเขียนลงใบเสร็จให้ผู้เช่าถือไป
--
-- ใช้ตัวนับชุดเดียวกับใบแจ้งหนี้/ใบเสร็จ (ตาราง document_counters) เพิ่ม doc_type = 'booking'
-- ได้เลขหน้าตา B2026080001 = 'B' + YYYYMM + ลำดับ 4 หลัก
-- doc_type ไม่มี CHECK ผูกไว้ จึงไม่ต้องแก้โครงตารางนั้น
--
-- ปล่อยให้เป็น NULL ได้ เพราะการจองที่บันทึกไว้ก่อนหน้านี้ไม่มีเลข และการย้อนไปออกเลข
-- ให้ทีหลังจะได้ลำดับที่ไม่ตรงกับความจริงว่าใครจองก่อนหลัง
ALTER TABLE room_bookings ADD COLUMN booking_number TEXT;

-- เลขที่ห้ามซ้ำ แต่แถวที่เป็น NULL ซ้ำกันได้ (SQLite ถือว่า NULL ไม่เท่ากับ NULL)
CREATE UNIQUE INDEX idx_room_bookings_number ON room_bookings (booking_number);
