-- บันทึกว่าหอนี้เดินตัวช่วยตั้งค่าครบ 8 ขั้นแล้วหรือยัง
--
-- ทำไมต้องมีคอลัมน์นี้ แทนที่จะเดาจากข้อมูลที่มี:
-- เดิมหน้ารวมหอเดาเอาว่า "มีห้องแล้ว = ตั้งค่าเสร็จ" ซึ่งผิด — หอที่สร้างผังห้องแล้วแต่ยัง
-- ไม่ได้ตั้งค่าเช่า ยังไม่ได้ตั้งสถานะ ยังไม่ได้ผูกค่าบริการ ก็นับว่ามีห้องเหมือนกัน
-- เจ้าของหอจึงหลุดเข้าหน้าทำงานที่มีเมนูข้างไปทั้งที่ค่าเช่ายังเป็น 0 ทุกห้อง แล้วออกบิล
-- เป็นศูนย์ทั้งหอโดยไม่มีอะไรเตือน
--
-- ไม่เก็บเป็น 0/1 แต่เก็บเป็นเวลา ISO เพราะอยากรู้ด้วยว่าตั้งค่าเสร็จเมื่อไหร่ เวลาไล่
-- ปัญหาย้อนหลังว่าข้อมูลชุดไหนเกิดก่อน/หลังการตั้งค่า
--
-- NULL = ยังตั้งค่าไม่เสร็จ (ค่าเริ่มต้นของทุกแถว รวมถึงหอที่มีอยู่ก่อนอัปเกรด)
ALTER TABLE apartments ADD COLUMN setup_completed_at TEXT;

-- หอที่มีห้องอยู่แล้วตอนอัปเกรด ถือว่าตั้งค่าเสร็จแล้ว ไม่งั้นหอที่ใช้งานจริงอยู่จะถูก
-- เด้งกลับเข้าตัวช่วยตั้งค่าใหม่ทั้งหมดหลังอัปเดตแอป
UPDATE apartments
   SET setup_completed_at = COALESCE(updated_at, created_at)
 WHERE apartment_id IN (
   SELECT DISTINCT f.apartment_id
     FROM floors f JOIN rooms r ON r.floor_id = f.floor_id
 );
