-- วันที่ผู้เช่าแจ้งย้ายออก
--
-- ต้นแบบแยกเป็นสองจังหวะ (คู่มือ yeeraf หัวข้อ "ยกเลิกสัญญาเช่า / ย้ายออก" ขั้น 2-4):
--   1) ปุ่ม "แจ้งย้ายออก" → กรอกวันที่แจ้ง → บันทึกค้างไว้บนการ์ดสัญญา (แก้ไขได้)
--   2) ปุ่มแดง "ยกเลิกสัญญา / ย้ายออก" → หน้าสรุปเงิน → ยืนยันพร้อม "วันที่ออก"
--
-- **วันที่แจ้ง กับ วันที่ออกจริง เป็นคนละวัน** และระยะห่างของสองวันนี้คือสิ่งที่กฎเงินประกัน
-- ของหอเราใช้ตัดสิน (แจ้งไม่ถึง 15 วัน = ริบ) จึงต้องเก็บวันแจ้งไว้ตั้งแต่วันที่แจ้งจริง
-- ไม่ใช่ให้มากรอกย้อนหลังตอนกดย้ายออก ซึ่งจะกลายเป็นตัวเลขที่แก้ให้เข้าทางได้เสมอ
--
-- อยู่ที่ `contracts` ไม่ใช่สร้างแถว `contract_terminations` แบบร่างรอไว้ เพราะตารางนั้นมี
-- `actual_move_out_date NOT NULL` ซึ่งตอนแจ้งยังไม่รู้ และแถวในตารางนั้นควรแปลว่า
-- "ย้ายออกจบแล้ว" อย่างเดียว ไม่ใช่มีสองความหมายปนกัน
--
-- NULL = ยังไม่ได้แจ้ง · ล้างกลับเป็น NULL ได้ถ้าผู้เช่าเปลี่ยนใจไม่ย้ายแล้ว
-- ตอนย้ายออกจริง ถ้ายังเป็น NULL แปลว่า "ออกโดยไม่แจ้งล่วงหน้า" (is_notice_given = 0)
ALTER TABLE contracts ADD COLUMN move_out_notice_date TEXT;

