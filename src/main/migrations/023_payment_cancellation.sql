-- **ยกเลิก ไม่ใช่ลบ และไม่ใช่คืนเงิน** — สามอย่างนี้คนละความหมายกันในบัญชี:
--   ลบ      = ใบนี้ไม่เคยมี → เลขที่ที่ยื่นให้ผู้เช่าไปแล้วจะชี้ไปที่ความว่างเปล่า
--   คืนเงิน = รับมาจริงแล้วจ่ายกลับ → เงินสองก้อนเดินเข้าออกจริง ซึ่งไม่ได้เกิดขึ้น
--   ยกเลิก  = ใบนี้ออกผิด ไม่นับ → ตรงกับความจริงคือ "เงินก้อนนี้ไม่เคยเข้า"
--
-- แถวยังอยู่ครบ เลขที่ใบเสร็จจึงไม่ถูกใช้ซ้ำ (document_counters ไม่ถอยอยู่แล้ว)
-- และเหตุผลถูกเก็บไว้ที่แถวเดิม ไม่ต้องมีตารางแยกแบบ invoice_deletions เพราะที่นั่น
