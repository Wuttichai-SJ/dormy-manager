-- เคสจริงที่ผู้ใช้ยกมา 2026-08-10: ผู้เช่ามาดูห้อง 01/03 วางเงินจอง 2,000 (= ครึ่งหนึ่ง
-- ของเงินประกัน 4,000) แล้วเข้าอยู่จริง 25/05 — เจ้าของหอต้องเก็บอีก 2,000 ในวันเข้าอยู่
--
-- ของเดิม: ฟอร์มทำสัญญาโชว์ "รวม (เก็บเพิ่ม) 2,000" ให้ดูตอนกรอก แล้วตัวเลขนั้นหายไป
-- กับหน้าจอ ไม่ได้ถูกเก็บที่ไหนเลย · `contracts.deposit_amount_cents` คือยอดที่ "ตกลงกัน"
-- ไม่ใช่ยอดที่ "รับมาแล้ว" · และเงินจองที่รับไปจริงไม่เคยเข้าตาราง payments เลย
-- รายงานใบเสร็จจึงมองไม่เห็นเงินก้อนนั้น
--
-- ทางแก้: **นับยอดที่รับแล้วจากใบเสร็จจริง ไม่เพิ่มคอลัมน์ให้พิมพ์มือ** ตัวเลขที่พิมพ์เอง
-- จะเพี้ยนจากเงินจริงในที่สุด ส่วนใบเสร็จเป็นความจริงที่ตรวจสอบย้อนหลังได้
--
-- ต้องรู้ว่าใบเสร็จของสัญญาใบไหนเป็น "เงินประกัน" เพราะใบเสร็จที่ผูกกับสัญญายังมีอย่างอื่น
-- ปนอยู่ (ค่าเช่าล่วงหน้า และการคืนเงินประกันตอนย้ายออกใน Phase 4)
--
-- ค่าที่ใช้: 'invoice' (ค่าบิล) · 'deposit' (เงินประกัน รวมเงินจองที่ถูกหักเป็นเงินประกัน)
--           'advance' (ค่าเช่าล่วงหน้า) · 'other'
-- SQLite ไม่มี ENUM — ตรวจค่าที่ JS ก่อนเขียนเสมอ (PAYMENT_PURPOSES ใน db/payments.js)

ALTER TABLE payments ADD COLUMN purpose TEXT;

-- แถวเดิม: ใบที่ผูกกับบิลคือค่าบิล ที่เหลือผูกกับสัญญาซึ่งมีแต่เงินประกัน/เงินล่วงหน้า
-- (ยังไม่เคยมีหน้าจอไหนออกใบเสร็จของสัญญาได้เลย แถวพวกนี้จึงมาจากชุดทดสอบเท่านั้น)
UPDATE payments SET purpose = CASE
  WHEN invoice_id IS NOT NULL THEN 'invoice'
  ELSE 'deposit'
END;
