-- ผู้ใช้มีสองบทบาทตายตัว: เจ้าของหอ (owner) กับพนักงาน (staff)
--
-- ที่มา: เจ้าของหออาจจ้างคนมาดูแลแทนในอนาคต (ผู้ใช้ยืนยัน 2026-08-14) คนที่จ้างมาต้อง
-- ทำงานประจำวันได้ทั้งหมด — จดมิเตอร์ ออกบิล รับเงิน ทำสัญญา ย้ายออก — แต่ของที่ลบแล้ว
-- หายหรือกระทบเงินย้อนหลังต้องสงวนไว้ให้เจ้าของ เพราะคนจ้างไม่ได้นั่งเฝ้าอยู่ด้วย
--
-- ทำไมเป็นคอลัมน์เดียวไม่ใช่เมทริกซ์สิทธิ์: หอสามตึกที่มีเจ้าของคนเดียวกับลูกจ้างหนึ่งคน
-- ไม่ต้องใช้ระบบสิทธิ์แบบตั้งค่าได้ และทุกอย่างที่ตั้งค่าได้คือของที่ต้องดูแลไปอีกยี่สิบปี
--
-- DEFAULT เป็น 'staff' ซึ่งเป็นสิทธิ์ต่ำสุดโดยตั้งใจ — โค้ดที่ลืมส่ง role มา ต้องได้บัญชีที่
-- ทำอะไรไม่ได้ ไม่ใช่บัญชีที่ลบได้ทุกอย่าง
ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'staff';

-- บัญชีที่มีอยู่แล้วคือเจ้าของ — ระบบเดิมสร้างผู้ใช้ได้คนเดียวเท่านั้น (auth:setup ทำงาน
-- เฉพาะตอนยังไม่มีใครในระบบเลย) คนที่มีอยู่จึงเป็นเจ้าของหอเสมอ
UPDATE users SET role = 'owner';

-- ตาราง RBAC สี่ใบที่ลอกมาจากสคีมาของต้นแบบตั้งแต่ 001_init.sql แต่ไม่เคยมีโค้ดบรรทัดไหน
-- แตะเลย (grep ทั้ง src เจอแค่ในไฟล์ migration เอง) — เป็นระบบสิทธิ์ของ SaaS หลายลูกค้า
--
-- ทิ้งไปเลยดีกว่าปล่อยไว้: ตารางเปล่าที่ชื่อว่า permissions จะทำให้คนที่มาอ่านโค้ดอีกสิบปี
-- เชื่อว่าสิทธิ์อยู่ในนั้น แล้วไปแก้ผิดที่ · ปลอดภัยเพราะไม่มีข้อมูลและไม่มีใครอ้างถึง
--
-- ลบลูกก่อนแม่ (role_permission / user_roles ชี้ไปที่ roles กับ permissions)
DROP TABLE IF EXISTS role_permission;
DROP TABLE IF EXISTS user_roles;
DROP TABLE IF EXISTS permissions;
DROP TABLE IF EXISTS roles;

-- **ไม่ได้แตะ `users_apartments`** ทั้งที่ยังไม่มีใครใช้เหมือนกัน — ตารางนั้นเป็นเรื่อง
-- "ผู้ใช้คนนี้เห็นหอไหนบ้าง" ซึ่งเป็นคนละเรื่องกับสิทธิ์ และเป็นสิ่งที่หอนี้อาจอยากได้จริง
-- ถ้าวันหนึ่งจ้างคนมาดูแลแยกตึก
